function tools() {
  const sf = source("src/mcpServer.ts");
  const calls = new Map();
  for (const node of sf.statements) {
    if (!ts.isFunctionDeclaration(node) || !node.name) continue;
    const children = new Set();
    visit(node, (child) => {
      if (
        ts.isCallExpression(child) &&
        ts.isIdentifier(child.expression) &&
        /^register.+Tools?$/.test(child.expression.text)
      )
        children.add(child.expression.text);
    });
    calls.set(node.name.text, children);
  }
  const reachable = (start) => {
    const found = new Set();
    const collect = (name) => {
      if (found.has(name)) return;
      found.add(name);
      for (const child of calls.get(name) ?? []) collect(child);
    };
    collect(start);
    return found;
  };
  const reads = reachable("registerReadTools");
  const writes = reachable("registerWriteTools");
  const context = { z };
  visit(sf, (node) => {
    if (
      ts.isVariableDeclaration(node) &&
      ["expectedContextSchema", "uiTargetSchema"].includes(node.name.getText(sf))
    )
      context[node.name.getText(sf)] = evaluate(node.initializer, sf, context);
  });
  const records = [];
  visit(sf, (node) => {
    if (
      !ts.isCallExpression(node) ||
      !ts.isPropertyAccessExpression(node.expression) ||
      node.expression.name.text !== "registerTool"
    )
      return;
    const name = evaluate(node.arguments[0], sf, context);
    const metadata = evaluate(node.arguments[1], sf, context);
    let parent = node.parent;
    while (parent && !ts.isFunctionDeclaration(parent)) parent = parent.parent;
    const registration = parent?.name?.text;
    if (!registration) throw new Error(`Cannot identify registration for ${name}`);
    if (!reads.has(registration) && !writes.has(registration))
      throw new Error(`Unclassified registration for ${name}: ${registration}`);
    // Descriptions are plain tool strings, not Markdown. Preserve literals such as
    // __CALLBACK__ instead of letting a formatter turn them into bold text.
    const description = metadata.description.replace(/[\\`*_{}[\]<>#]/g, "\\$&");
    records.push({
      name,
      description,
      inputSchema: z.toJSONSchema(metadata.inputSchema, { unrepresentable: "any" }),
      tokenRequired: writes.has(registration) && !reads.has(registration),
      registration,
      line: sf.getLineAndCharacterOfPosition(node.getStart()).line + 1,
    });
  });
  if (records.length === 0 || new Set(records.map((r) => r.name)).size !== records.length)
    throw new Error("Missing or duplicate MCP registrations");
  return records;
}

function cli() {
  const sf = source("harness/src/cli.ts");
  let help;
  visit(sf, (node) => {
    if (ts.isVariableDeclaration(node) && node.name.getText(sf) === "HELP")
      help = evaluate(node.initializer, sf, {});
  });
  // Commands that bin/doodlebot.cjs handles before tsx loads (`handledBy: "bin"` in
  // commands.ts, such as `update`) are not dispatched by cli.ts but are still commands.
  const list = source("harness/src/commands.ts");
  let entries;
  visit(list, (node) => {
    if (ts.isVariableDeclaration(node) && node.name.getText(list) === "commands")
      entries = evaluate(node.initializer, list, {});
  });
  if (!Array.isArray(entries)) throw new Error("harness/src/commands.ts lists no commands");
  const bin = entries.filter((entry) => entry.handledBy === "bin").map((entry) => entry.name);
  const commands = [...new Set([...dispatchedCommands(sf), ...bin])].sort();
  if (!help || commands.length === 0) throw new Error("CLI inventory is empty");
  return { help, commands };
}

