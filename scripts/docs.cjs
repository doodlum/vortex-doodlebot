if (!write) {
  const map = JSON.parse(read("scripts/documentation-map.json"));
  for (const group of map.groups)
    for (const file of [...group.human, ...group.ai])
      if (!fs.existsSync(path.join(root, file)))
        errors.push(`Missing paired documentation: ${file}`);
  const base = process.env.DOODLEBOT_DOCS_BASE;
  const changed = new Set();
  const git = (args) =>
    cp
      .execFileSync("git", args, { cwd: root, encoding: "utf8" })
      .trim()
      .split(/\r?\n/)
      .filter(Boolean);
  try {
    if (base && !/^0+$/.test(base))
      git(["diff", "--name-only", base + "...HEAD"]).forEach((file) => changed.add(file));
    git(["diff", "--name-only", "HEAD"]).forEach((file) => changed.add(file));
    git(["ls-files", "--others", "--exclude-standard"]).forEach((file) => changed.add(file));
    for (const group of map.groups) {
      if (
        ![...changed].some((file) =>
          group.sources.some((pattern) => new RegExp(pattern).test(file)),
        )
      )
        continue;
      if (!group.human.some((file) => changed.has(file)))
        errors.push(
          `${group.name}: update a mapped human page in the same change (${group.human.join(", ")}).`,
        );
      if (!group.ai.some((file) => changed.has(file)))
        errors.push(
          `${group.name}: update a mapped AI contract/manual in the same change (${group.ai.join(", ")}).`,
        );
    }
    // A shared AI manual covers several areas. A prose-only edit needs the related
    // human explanation, rather than unrelated edits to every guide it happens to index.
    for (const file of changed) {
      const groups = map.groups.filter((group) => group.ai.includes(file));
      if (groups.length && !groups.some((group) => group.human.some((human) => changed.has(human))))
        errors.push(`${file}: update a mapped human companion in the same change.`);
    }
  } catch (error) {
    errors.push("Documentation change accounting failed: " + error.message);
  }
  // Published pages cannot silently link outside the human site to agent instructions.
  const walk = (dir) =>
    fs
      .readdirSync(dir, { withFileTypes: true })
      .flatMap((entry) =>
        entry.isDirectory() ? walk(path.join(dir, entry.name)) : [path.join(dir, entry.name)],
      );
  for (const file of walk(path.join(root, "docs")).filter((file) => file.endsWith(".md"))) {
    const body = fs.readFileSync(file, "utf8");
    if (/\]\([^)]*(?:AGENTS\.md|AGENT-WORKFLOW\.md|KNOWLEDGE-ROUTES\.md|\/\.claude\/)/.test(body))
      errors.push(
        `${path.relative(root, file)} links to AI instructions; explain the operation for human readers instead.`,
      );
  }
}
