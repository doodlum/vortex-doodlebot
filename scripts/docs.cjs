function frontmatter(file) {
  const match = /^---\n([\s\S]*?)\n---\n/.exec(read(file));
  if (!match) throw new Error(`${file} has no frontmatter`);
  const fields = {};
  for (const line of match[1].split("\n")) {
    const field = /^([\w-]+):\s*(.*)$/.exec(line);
    if (!field) continue;
    const value = field[2].trim();
    fields[field[1]] = value.startsWith('"') ? JSON.parse(value) : value;
  }
  return fields;
}

function pluginCommands() {
  const marketplace = JSON.parse(read(".claude-plugin/marketplace.json"));
  const plugins = marketplace.plugins.map((plugin) => plugin.name);
  if (plugins.join(",") !== PLUGIN)
    throw new Error(`Marketplace plugins (${plugins.join(", ")}) differ from ${PLUGIN}`);
  const skillsDir = path.join(root, "plugins", PLUGIN, "skills");
  const onDisk = fs
    .readdirSync(skillsDir, { withFileTypes: true })
    .filter(
      (entry) => entry.isDirectory() && fs.existsSync(path.join(skillsDir, entry.name, "SKILL.md")),
    )
    .map((entry) => entry.name)
    .sort();
  const expected = COMMAND_GROUPS.flatMap((group) => group.commands).sort();
  if (onDisk.join(",") !== expected.join(","))
    throw new Error(
      `Skills of plugin ${PLUGIN} (${onDisk.join(", ")}) differ from COMMAND_GROUPS (${expected.join(", ")})`,
    );
  return COMMAND_GROUPS.map((group) => ({
    title: group.title,
    description: group.description,
    commands: group.commands.map((name) => {
      const file = `plugins/${PLUGIN}/skills/${name}/SKILL.md`;
      const fields = frontmatter(file);
      if (fields.name !== name) throw new Error(`${file} names itself ${fields.name}`);
      if (!fields.description) throw new Error(`${file} has no description`);
      return {
        command: `/${PLUGIN}:${name}`,
        description: fields.description.replace(new RegExp(`^${PLUGIN}:\\s*`, "i"), ""),
        argumentHint: fields["argument-hint"],
        file,
      };
    }),
  }));
}

function api() {
  const entry = source("harness/src/kit.ts");
  const modules = new Map([
    ["config", "config.ts"],
    ["mcpClient", "mcpClient.ts"],
    ["cdp", "cdp.ts"],
    ["instance", "instance.ts"],
    ["jsonFile", "jsonFile.ts"],
    ["collectionCompletion", "collectionCompletion.ts"],
  ]);
  for (const statement of entry.statements) {
    if (
      ts.isExportDeclaration(statement) &&
      statement.moduleSpecifier &&
      ts.isNamespaceExport(statement.exportClause)
    )
      modules.set(
        statement.exportClause.name.text,
        statement.moduleSpecifier.text.replace("./", "") + ".ts",
      );
  }
  return [...modules].map(([name, file]) => {
    const relative = path.posix.normalize("harness/src/" + file);
    const sf = source(relative);
    const symbols = [];
    for (const node of sf.statements) {
      if (!exported(node)) continue;
      let signature;
      if (ts.isFunctionDeclaration(node))
        signature =
          text(node, sf)
            .slice(0, node.body ? node.body.pos - node.getStart() : undefined)
            .trim() + ";";
      else if (ts.isClassDeclaration(node))
        signature =
          `export class ${node.name.text} {\n` +
          node.members
            .filter(
              (m) =>
                !m.name?.getText(sf).startsWith("#") &&
                !m.modifiers?.some((mod) => mod.kind === ts.SyntaxKind.PrivateKeyword),
            )
            .map((m) =>
              m.body
                ? m
                    .getText(sf)
                    .slice(0, m.body.pos - m.getStart())
                    .trim() + ";"
                : m.getText(sf),
            )
            .join("\n") +
          "\n}";
      else if (ts.isInterfaceDeclaration(node) || ts.isTypeAliasDeclaration(node))
        signature = text(node, sf);
      else if (ts.isVariableStatement(node))
        signature = node.declarationList.declarations
          .filter((d) => ts.isIdentifier(d.name))
          .map((d) => `export const ${d.name.text}${d.type ? ": " + d.type.getText(sf) : ""};`)
          .join("\n");
      else continue;
      const docs = (node.jsDoc ?? [])
        .map((d) => (typeof d.comment === "string" ? d.comment : ""))
        .join("\n");
      symbols.push({
        name: node.name?.getText(sf),
        signature,
        docs,
        line: sf.getLineAndCharacterOfPosition(node.getStart()).line + 1,
      });
    }
    return { name, file: relative, symbols };
  });
}

function result(file, expected) {
  expected = cp.execFileSync(
    process.execPath,
    [path.join(repository, "node_modules/oxfmt/bin/oxfmt"), "--stdin-filepath", file],
    { cwd: root, input: expected, encoding: "utf8", maxBuffer: 10 * 1024 * 1024 },
  );
  if (write) {
    fs.mkdirSync(path.dirname(path.join(root, file)), { recursive: true });
    fs.writeFileSync(path.join(root, file), expected);
  } else if (!fs.existsSync(path.join(root, file)) || read(file) !== expected)
    errors.push(`${file} is stale; run pnpm run docs:generate and review the result.`);
}

